-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

CREATE TABLE accounts (
    id         UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    name       TEXT        NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
    kind       TEXT        NOT NULL CHECK (kind IN ('USER', 'SYSTEM')),
    currency   CHAR(3)     NOT NULL CHECK (currency IN ('INR', 'USD')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Hot, mutable cache row: the only thing locked and rewritten per transfer.
CREATE TABLE account_balances (
    account_id     UUID        PRIMARY KEY REFERENCES accounts (id),
    balance        BIGINT      NOT NULL DEFAULT 0,
    allow_negative BOOLEAN     NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT balance_non_negative_unless_allowed CHECK (allow_negative OR balance >= 0)  -- I4 backstop
);

CREATE TABLE transactions (
    id          UUID        PRIMARY KEY,  -- generated by the app (needed by idempotency_keys first)
    kind        TEXT        NOT NULL CHECK (kind = 'TRANSFER'),
    description TEXT        CHECK (char_length(description) <= 255),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE entries (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id UUID   NOT NULL REFERENCES transactions (id),
    account_id     UUID   NOT NULL REFERENCES accounts (id),
    amount         BIGINT NOT NULL CHECK (amount <> 0)
);

CREATE INDEX entries_account_id_id_idx ON entries (account_id, id);
CREATE INDEX entries_transaction_id_idx ON entries (transaction_id);

CREATE TABLE idempotency_keys (
    key            TEXT        PRIMARY KEY CHECK (char_length(key) BETWEEN 1 AND 255),
    request_hash   BYTEA       NOT NULL,
    -- Deferred: this row is inserted before its transaction row, inside the same DB transaction.
    transaction_id UUID        NOT NULL REFERENCES transactions (id) DEFERRABLE INITIALLY DEFERRED,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- I1: every transaction balances (checked at COMMIT)
-- ---------------------------------------------------------------------------

CREATE FUNCTION assert_transaction_balanced() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    tx_id        UUID;
    total        BIGINT;
    n_entries    INT;
    n_currencies INT;
BEGIN
    IF TG_TABLE_NAME = 'entries' THEN
        tx_id := NEW.transaction_id;
    ELSE
        tx_id := NEW.id;
    END IF;

    SELECT COALESCE(SUM(e.amount), 0), COUNT(*), COUNT(DISTINCT a.currency)
      INTO total, n_entries, n_currencies
      FROM entries e
      JOIN accounts a ON a.id = e.account_id
     WHERE e.transaction_id = tx_id;

    IF total <> 0 OR n_entries < 2 OR n_currencies <> 1 THEN
        RAISE EXCEPTION 'transaction % is unbalanced (sum=%, entries=%, currencies=%)',
                        tx_id, total, n_entries, n_currencies
              USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END
$$;

CREATE CONSTRAINT TRIGGER entries_balanced
    AFTER INSERT ON entries
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION assert_transaction_balanced();

-- Catches a transaction row with zero entries, which would never fire entries_balanced.
CREATE CONSTRAINT TRIGGER transactions_have_entries
    AFTER INSERT ON transactions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION assert_transaction_balanced();

-- ---------------------------------------------------------------------------
-- I6: the log is append-only
-- ---------------------------------------------------------------------------

CREATE FUNCTION forbid_log_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% on % is forbidden: the ledger log is append-only', TG_OP, TG_TABLE_NAME;
END
$$;

CREATE TRIGGER transactions_append_only BEFORE UPDATE OR DELETE ON transactions
    FOR EACH ROW EXECUTE FUNCTION forbid_log_mutation();
CREATE TRIGGER entries_append_only BEFORE UPDATE OR DELETE ON entries
    FOR EACH ROW EXECUTE FUNCTION forbid_log_mutation();
CREATE TRIGGER transactions_no_truncate BEFORE TRUNCATE ON transactions
    FOR EACH STATEMENT EXECUTE FUNCTION forbid_log_mutation();
CREATE TRIGGER entries_no_truncate BEFORE TRUNCATE ON entries
    FOR EACH STATEMENT EXECUTE FUNCTION forbid_log_mutation();

